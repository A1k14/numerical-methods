import math


# =====================================================================
# 1. АЛГЕБРАЇЧНЕ РІВНЯННЯ
# Приклад: x³ - 2x - 5 = 0
# Дійсний корінь на відрізку [2, 3]: x ≈ 2.09455
# =====================================================================

def f_alg(x: float) -> float:
    """Саме алгебраїчне рівняння: f(x) = x³ - 2x - 5"""
    return x**3 - 2 * x - 5

def df_alg(x: float) -> float:
    """Перша похідна f'(x) = 3x² - 2 (потрібна для методу Ньютона)"""
    return 3 * x**2 - 2

def d2f_alg(x: float) -> float:
    """Друга похідна f''(x) = 6x (потрібна для методу хорд)"""
    return 6 * x

def phi_alg(x: float) -> float:
    """
    Ітераційна функція φ(x) для методу простої ітерації: x = φ(x).
    Для x³ - 2x - 5 = 0:
    x³ = 2x + 5  =>  x = (2x + 5)^(1/3)
    (умова збіжності |φ'(x)| < 1 виконується на [2, 3])
    """
    val = 2 * x + 5
    if val < 0:
        return -((-val) ** (1 / 3))
    return val ** (1 / 3)

