# =====================================================================
# 2. ТРАНСЦЕНДЕНТНЕ РІВНЯННЯ
# Приклад: cos(x) - x = 0
# Дійсний корінь на відрізку [0, 1]: x ≈ 0.739085
# =====================================================================

def f_trans(x: float) -> float:
    """Саме трансцендентне рівняння: f(x) = cos(x) - x"""
    return math.cos(x) - x

def df_trans(x: float) -> float:
    """Перша похідна f'(x) = -sin(x) - 1 (потрібна для методу Ньютона)"""
    return -math.sin(x) - 1.0

def d2f_trans(x: float) -> float:
    """Друга похідна f''(x) = -cos(x) (потрібна для методу хорд)"""
    return -math.cos(x)

def phi_trans(x: float) -> float:
    """
    Ітераційна функція φ(x) для методу простої ітерації: x = φ(x).
    Для cos(x) - x = 0:  x = cos(x)
    (умова збіжності |φ'(x)| = |-sin(x)| <= sin(1) ≈ 0.841 < 1 на [0, 1])
    """
    return math.cos(x)

